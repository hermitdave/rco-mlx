def strip_imports(text: str) -> str:
    out, skipping = [], False
    for line in text.splitlines():
        if skipping:
            if ")" in line:
                skipping = False
            continue
        if line.rstrip().endswith("(") and any(r.match(line) for r in STRIP):
            skipping = True
            continue
        if any(r.match(line) for r in STRIP):
            continue
        for rx, sub in REPLACE:
            line = rx.sub(sub, line)
        out.append(line)
    return "\n".join(out)


def func_block(path: Path, name: str) -> str:
    """Extract a top-level def/class block (including decorators) by name."""
    lines = path.read_text().splitlines()
    start = None
    for i, l in enumerate(lines):
        if re.match(rf"^(def|class) {re.escape(name)}\b", l):
            start = i
            break
    if start is None:
        raise SystemExit(f"{name} not found in {path}")
    while start > 0 and lines[start - 1].startswith("@"):
        start -= 1
    end = len(lines)
    for j in range(start + 1, len(lines)):
        if re.match(r"^(def|class|@)\s", lines[j]) or re.match(r"^[A-Z_]+ *=", lines[j]):
            end = j
            break
    return "\n".join(lines[start:end]).rstrip()


