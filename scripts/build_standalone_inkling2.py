def splice(
    embeddings: mx.array,
    inputs: mx.array,
    *,
    rows: mx.array,
    token_id: int,
) -> mx.array:
    """The embeddings with the rows, in order, at the token_id positions of inputs."""
    if rows.shape[0] == 0:
        return embeddings
    mask = inputs == token_id
    idx = mx.cumsum(mask.flatten()).reshape(mask.shape) - 1
    idx = mx.clip(idx, 0, rows.shape[0] - 1)
    selected = rows[idx].astype(embeddings.dtype)
    return mx.where(mask[..., None], selected, embeddings)


def gather_last_axis(x: mx.array, group: mx.distributed.Group) -> mx.array:
    """Gather the last axis of ``x``, which is split across ``group``."""
    n, size = group.size(), x.shape[-1]
    parts = mx.distributed.all_gather(x.reshape(-1, size), group=group)
    parts = parts.reshape(n, -1, size).transpose(1, 0, 2)
    return parts.reshape(*x.shape[:-1], n * size)


class PipelineMixin:
    def __init__(self):
        super().__init__()
        self.pipeline_rank = 0
        self.pipeline_size = 1
        self.start_idx = 0
        self.end_idx = None

    @property
    def pipeline_layers(self):
        return self.layers[self.start_idx : self.end_idx]

    def pipeline(self, group, split=None):
        self.pipeline_rank = group.rank()
        self.pipeline_size = group.size()
        if split is None:
            base, extra = divmod(len(self.layers), self.pipeline_size)
            split = [base + (1 if r < extra else 0) for r in range(self.pipeline_size)]
        if len(split) != self.pipeline_size:
            raise ValueError(
                f"split has {len(split)} entries for group size {self.pipeline_size}"
            )
        if any(s <= 0 for s in split) or sum(split) != len(self.layers):
            raise ValueError(
                f"split {split} must be positive and sum to {len(self.layers)} layers"
            )
        self.start_idx = sum(split[self.pipeline_rank + 1 :])
        self.end_idx = self.start_idx + split[self.pipeline_rank]
        self.layers = self.layers[: self.end_idx]
        self.layers[: self.start_idx] = [None] * self.start_idx


